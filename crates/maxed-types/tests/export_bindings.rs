/// JSON and its compile-checked TS counterpart come from the same Rust value.
#[test]
fn export_p2_fixture() {
    let directory =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../app/ui/tests/fixtures");
    std::fs::create_dir_all(&directory).unwrap();
    let text = serde_json::to_string_pretty(&demo::demo_snapshot()).unwrap();
    std::fs::write(directory.join("t0-live.json"), format!("{text}\n")).unwrap();
    std::fs::write(
        directory.join("t0-live.ts"),
        format!(
            "// Generated by maxed-types export_p2_fixture; synthetic data only.\n\
             import type {{ LiveSnapshot }} from '../../src/lib/bindings/LiveSnapshot';\n\
             export default {text} satisfies LiveSnapshot;\n"
        ),
    )
    .unwrap();
}

/// Export the same typed synthetic fixtures as JSON for UI tests.
#[test]
fn export_demo_fixture() {
    let directory = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    std::fs::create_dir_all(&directory).unwrap();
    let fixture = serde_json::json!({
        "snapshot": demo::demo_snapshot(),
        "catalog": demo::demo_catalog(),
        "home_summary": demo::demo_home_summary(),
        "run_page": demo::demo_run_page(),
        "run_story": demo::demo_run_story(),
    });
    let mut text = serde_json::to_string_pretty(&fixture).unwrap();
    text.push('\n');
    std::fs::write(directory.join("p1-demo.json"), text).unwrap();
}
